#!/usr/bin/env python3
"""Compile authored multitrack lessons; never synthesize lesson content."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

def dart(value):
    if isinstance(value, str):
        return json.dumps(value, ensure_ascii=False).replace('$', r'\$')
    if isinstance(value, list):
        return '[' + ', '.join(dart(v) for v in value) + ']'
    if isinstance(value, dict):
        return '{' + ', '.join(dart(k) + ': ' + dart(v) for k, v in value.items()) + '}'
    return str(value)

def sql(value):
    return "'" + value.replace("'", "''") + "'"

def build():
    data = json.loads((ROOT / 'content/academy_extensions.json').read_text())
    assert data['schema_version'] == 1
    lessons = data['lessons']
    assert len(lessons) == 80
    assert len({x['id'] for x in lessons}) == 80
    lines = ["// Generated by scripts/build-academy-catalog.py. Edit authored JSON.\nimport '../lesson_models.dart';\n\nconst academyExtensions = <Lesson>["]
    guides = ['const academyExtensionGuides = <String, LessonGuide>{']
    migrations = ["-- Additive academy expansion: keep existing course IDs, lessons and progress."]
    migrations.append('insert into public.courses(id,title_my,title_en) values\n' + ',\n'.join('('+','.join(map(sql,[t['id'],t['my'],t['en']]))+')' for t in data['tracks']) + '\non conflict(id) do nothing;')
    rows = []
    seen = {f'py-{i:02d}' for i in range(1,41)}
    for lesson in lessons:
        assert lesson['track'] in ('programming','web','linux','security')
        assert set(lesson['prerequisites']) <= seen
        seen.add(lesson['id'])
        guide = lesson['guide']
        for lang in ('my','en'):
            assert len(guide[lang]['body']) >= 300, (lesson['id'],lang)
            assert all(guide[lang].get(k) for k in ('objectives','lines','mistake','hint','challenge','question','explanation'))
        assert len(guide['myOptions']) == len(guide['enOptions']) == 3
        assert 0 <= guide['correct'] < 3
        fields = {k:lesson[k] for k in ('id','track','language','level','environment','code','prerequisites','flow')}
        fields.update(titleMy=lesson['title']['my'],titleEn=lesson['title']['en'],summaryMy=guide['my']['objectives'],bodyMy=guide['my']['body'],challengeMy=guide['my']['challenge'],answer=lesson['solution'])
        lines.append('  Lesson(' + ', '.join(k+': '+dart(v) for k,v in fields.items()) + '),')
        guides.append(dart(lesson['id'])+': LessonGuide('+', '.join(k+': '+dart(v) for k,v in guide.items())+'),')
        rows.append('('+','.join([sql(lesson['id']),sql(lesson['track']),sql(lesson['title']['my']),sql(lesson['title']['en']),str(int(lesson['id'].split('-')[-1]))])+')')
    lines.append('];\n')
    guides.append('};\n')
    migrations.append('insert into public.lessons(id,course_id,title_my,title_en,sort_order) values\n'+',\n'.join(rows)+'\non conflict(id) do nothing;\n')
    return {'mobile/lib/generated/academy_extensions.dart':'\n'.join(lines+guides),'database/migrations/008_academy_tracks.sql':'\n'.join(migrations)}

if __name__ == '__main__':
    parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');args=parser.parse_args()
    for name,text in build().items():
        path=ROOT/name
        if args.check:
            if not path.exists() or path.read_text()!=text: raise SystemExit('Catalog drift: '+name)
        else:
            path.parent.mkdir(parents=True,exist_ok=True);path.write_text(text)
    print('Academy catalog '+('checked' if args.check else 'compiled'))
