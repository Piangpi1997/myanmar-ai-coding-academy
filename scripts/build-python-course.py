#!/usr/bin/env python3
"""Compile original curriculum into offline Dart and additive SQL; --check in CI.

This is an encoding/build step. It does not generate instructional text.
"""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def dart(value):
    if isinstance(value, str):
        return json.dumps(value, ensure_ascii=False).replace('$', r'\$')
    if isinstance(value, list):
        return '[' + ', '.join(dart(item) for item in value) + ']'
    if isinstance(value, dict):
        return '{' + ', '.join(dart(key) + ': ' + dart(item) for key, item in value.items()) + '}'
    return str(value)


def sql(value):
    return "'" + value.replace("'", "''") + "'"


def build():
    data = json.loads((ROOT / 'content/python_course.json').read_text())
    assert data['schema_version'] == 1
    lessons = data['lessons']
    assert len({lesson['id'] for lesson in lessons}) == len(lessons)
    source = "// Generated by scripts/build-python-course.py; edit content/python_course.json.\nimport '../lesson_models.dart';\n\nconst extendedLessons = <Lesson>[\n"
    guides = 'const extendedGuides = <String, LessonGuide>{\n'
    rows = []
    for number, lesson in enumerate(lessons, 13):
        assert lesson['id'] == f'py-{number:02d}'
        assert lesson['level'] in ('beginner', 'intermediate', 'advanced', 'professional')
        assert lesson['environment'] in ('sandbox', 'computer')
        assert len(lesson['flow']) >= 3
        for locale in ('my', 'en'):
            assert len(lesson['guide'][locale]['body']) > 650, lesson['id']
            assert all(lesson['guide'][locale].get(field) for field in ('objectives', 'lines', 'mistake', 'hint', 'challenge', 'question', 'explanation'))
        assert len(lesson['guide']['myOptions']) == len(lesson['guide']['enOptions']) >= 3
        assert 0 <= lesson['guide']['correct'] < len(lesson['guide']['enOptions'])
        fields = {'id': lesson['id'], 'titleMy': lesson['title']['my'], 'titleEn': lesson['title']['en'], 'summaryMy': lesson['guide']['my']['objectives'], 'bodyMy': lesson['guide']['my']['body'], 'code': lesson['code'], 'challengeMy': lesson['guide']['my']['challenge'], 'answer': lesson['solution'], 'level': lesson['level'], 'environment': lesson['environment'], 'prerequisites': lesson['prerequisites'], 'flow': lesson['flow']}
        source += '  Lesson(' + ', '.join(key + ': ' + dart(value) for key, value in fields.items()) + '),\n'
        guides += dart(lesson['id']) + ': LessonGuide(' + ', '.join(key + ': ' + dart(value) for key, value in lesson['guide'].items()) + '),\n'
        rows.append('(' + ','.join([sql(lesson['id']), "'python-zero'", sql(lesson['title']['my']), sql(lesson['title']['en']), str(number)]) + ')')
    source += '];\n\n' + guides + '};\n'
    # Never rewrite the first twelve lessons or existing completion rows.
    migration = '-- Original course expansion; apply after 004. Preserve existing IDs and progress.\n'
    if rows:
        migration += 'insert into public.lessons(id,course_id,title_my,title_en,sort_order) values\n' + ',\n'.join(rows) + '\non conflict(id) do nothing;\n'
    return {'mobile/lib/generated/python_course.dart': source, 'database/migrations/005_python_course.sql': migration}


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    for relative, expected in build().items():
        target = ROOT / relative
        if args.check:
            # Dart formatting is deliberately excluded: generated source is deterministic.
            if not target.exists() or target.read_text() != expected:
                raise SystemExit(f'Curriculum out of sync: {relative}')
        else:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(expected)
    print('Python curriculum build checked' if args.check else 'Python curriculum compiled')
